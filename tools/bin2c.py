"""Turn a binary file into a C source file defining a byte array.

    bin2c.py <symbol> <input | -> <output.c>

Used to embed the user-mode self-test program in the kernel image, so the
suite can run a ring-3 program on a machine with no disk at all.  An input
of `-` produces an empty array: that is what an architecture with no user
runtime yet gets, and the kernel test reports itself skipped.

The output is plain C rather than an assembler .incbin so that it lives in
architecture-neutral code and passes scripts/check-portability.sh.
"""
import sys


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2

    symbol, src, dst = sys.argv[1:]
    data = b"" if src == "-" else open(src, "rb").read()

    out = [
        "/* Generated by tools/bin2c.py.  Do not edit, do not commit. */",
        "#include <haven/types.h>",
        f"extern const uint8_t {symbol}[];",
        f"extern const size_t {symbol}_size;",
        f"const size_t {symbol}_size = {len(data)};",
        f"const uint8_t {symbol}[] = {{",
    ]
    for i in range(0, len(data), 16):
        out.append("\t" + ",".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    if not data:
        out.append("\t0")
    out.append("};")

    with open(dst, "w") as f:
        f.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
